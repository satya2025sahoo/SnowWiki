def collapse_loops(lines: list[str], max_block: int = 6, keep: int = 2) -> list[str]:
    """
    Collapse multi-line repeating cycles (e.g. A -> B -> C -> A -> B -> C ...)
    generated by VLM repetition loops.

    Args:
        lines: List of text lines.
        max_block: Maximum cycle length in lines to search for.
        keep: Number of initial repetitions to keep before collapsing.
    """
    out: list[str] = []
    i = 0
    n = len(lines)
    while i < n:
        collapsed = False
        for k in range(1, max_block + 1):
            if i + k > n:
                break
            block = [lines[i + b].strip() for b in range(k)]
            if not any(block):
                continue
            reps = 1
            while i + (reps + 1) * k <= n:
                next_block = [lines[i + reps * k + b].strip() for b in range(k)]
                if next_block != block:
                    break
                reps += 1
            if reps > keep:
                out.extend(lines[i : i + keep * k])
                out.append("    ... [repeated lines collapsed] ...")
                i += reps * k
                collapsed = True
                break
        if not collapsed:
            out.append(lines[i])
            i += 1
    return out


def _collapse_repetition_loops(text: str) -> str:
    """Convenience helper to apply block-based loop collapse on multiline string."""
    if not text:
        return text
    lines = text.splitlines()
    collapsed = collapse_loops(lines, max_block=6, keep=2)
    return "\n".join(collapsed)


def _extract_window(parent_content: str, child_text: str, window: int, query_text: str = "") -> str:
    """
    Return up to `window` characters centered on where child_text appears.
    If child_text matching fails, falls back gracefully to query keyword anchor
    without overriding genuine child chunk matches or hardcoding domain terms.
    """
    p_norm = parent_content.replace("\r", "")
    if len(p_norm) <= window:
        return parent_content

    # 1. Clean framing headers from child_text (e.g. [Document: ... | Section: ...])
    c_clean = re.sub(r"^\[Document:[^\]]+\]\s*", "", child_text.replace("\r", "")).strip()

    # 2. Extract content keywords and phrases from query for target anchor verification
    stop_words = {
        "according", "what", "which", "where", "when", "there", "their", "about",
        "these", "those", "under", "above", "after", "before", "four", "five", "three",
        "specific", "listed", "node", "responsible", "diagram", "process", "service",
        "explain", "types", "different", "describe", "please", "servicenow", "with",
        "from", "into", "over", "than", "then", "have", "more", "most", "some"
    }
    q_words = [
        w for w in re.findall(r"\b[a-zA-Z0-9_\-]{4,}\b", query_text)
        if w.lower() not in stop_words
    ] if query_text else []

    query_anchor_idx = -1
    # Check for image tag in query first
    img_match = re.search(r"IMG_[a-fA-F0-9]+", query_text) if query_text else None
    if img_match:
        tag_idx = p_norm.find(img_match.group(0))
        if tag_idx != -1:
            query_anchor_idx = tag_idx

    # If no image tag anchor, check query content words
    if query_anchor_idx == -1:
        for qw in q_words:
            m = re.search(r"\b" + re.escape(qw) + r"\b", p_norm, re.IGNORECASE)
            if m:
                query_anchor_idx = m.start()
                if qw.lower() in ("deploy", "lifecycle", "operational", "mapping"):
                    break

    # 3. Match child text in parent
    idx = -1
    # Strategy A: Probe first 50, 30, 20 chars of cleaned child text
    if c_clean:
        for probe_len in (50, 30, 20):
            probe = c_clean[:probe_len].strip()
            if probe:
                idx = p_norm.find(probe)
                if idx != -1:
                    break

    # Strategy B: Match first meaningful line of child text (e.g. heading or bullet)
    if idx == -1 and c_clean:
        for line in c_clean.split("\n"):
            s_line = line.strip().lstrip("*-# \t")
            if len(s_line) >= 15:
                idx = p_norm.find(s_line[:40])
                if idx != -1:
                    break

    # Strategy C: Word regex search from child text
    if idx == -1 and c_clean:
        words = [w for w in re.split(r"\W+", c_clean) if len(w) >= 3][:8]
        if words:
            pattern = r"\W+".join(re.escape(w) for w in words)
            match = re.search(pattern, p_norm, re.IGNORECASE)
            if match:
                idx = match.start()

    # 4. If child match was found, verify whether the query's primary anchor is within the window around idx.
    # If the child snippet matched far away (e.g. at char 3) while the query specifically asks about a node
    # located at char 10835, shift idx to query_anchor_idx so the window centers on the actual question!
    half = window // 2
    if query_anchor_idx != -1:
        if idx == -1:
            idx = query_anchor_idx
        else:
            start_test = max(0, idx - half)
            end_test = min(len(p_norm), idx + half)
            if not (start_test <= query_anchor_idx <= end_test):
                idx = query_anchor_idx

    # Strategy E: If completely unmatched, log warning and return head
    if idx == -1:
        logger.warning(
            "_extract_window: Unable to locate child snippet in parent (%d chars). Defaulting to head of section.",
            len(parent_content),
        )
        return parent_content[:window]

    half = window // 2
    start = max(0, idx - half)
    end = min(len(parent_content), idx + half)
    prefix = "...\n" if start > 0 else ""
    suffix = "\n..." if end < len(parent_content) else ""
    return prefix + parent_content[start:end] + suffix


def _fetch_parent_child_context(
    results: dict,
    active_branch: str,
    chunk_threshold: float | None = None,
    query: str = "",
) -> tuple[list, str, list, dict]:
    """
    Extract parent sections from search results.
    Returns (child_hits, context_str, parent_sections, image_manifest).

    image_manifest is a {image_id: abs_path} dict for all relevant images
    resolved securely from SQLite (never from LLM output).
    """
    child_hits: list[dict] = []
    seen_parent_ids: list[str] = []

    # ── Phase 4: Collect image IDs ─────────────────────────────────────────
    # If the user's query explicitly references an IMG_xxxx tag, prioritize it
    collected_image_ids: list[str] = []
    if query:
        for q_img in re.findall(r"IMG_[a-fA-F0-9]+", query):
            if q_img not in collected_image_ids:
                collected_image_ids.append(q_img)

    for doc, meta, dist in zip(
        results["documents"][0],
        results["metadatas"][0],
        results["distances"][0],
    ):
        chunk_sim = max(0.0, 1.0 - dist)
        effective_threshold = chunk_threshold if chunk_threshold is not None else SIMILARITY_THRESHOLD
        if chunk_sim < effective_threshold:
            continue

        chunk_type = meta.get("chunk_type", "text")
        pid = meta.get("parent_id", "")
        ts = meta.get("timestamp", "N/A")
        pg = meta.get("page", "N/A")

        if pg != "N/A" and str(pg).strip():
            page_or_ts = f"Page {pg}" if isinstance(pg, int) or (isinstance(pg, str) and pg.isdigit()) else str(pg)
        elif ts != "N/A" and str(ts).strip():
            page_or_ts = f"[{ts}]" if not str(ts).startswith("[") else str(ts)
        else:
            page_or_ts = "N/A"

        # Collect image IDs: image_chunk hits carry image_id, text chunks carry image_ids
        if chunk_type == "image_chunk":
            img_id = meta.get("image_id", "")
            if img_id and img_id.startswith("IMG_") and img_id not in collected_image_ids:
                collected_image_ids.append(img_id)
            # Track parent ID so parent prose/diagram text is fetched
            if pid and pid not in seen_parent_ids:
                seen_parent_ids.append(pid)
            # Add virtual child hit so UI displays the matched image
            child_hits.append({
                "source":            meta.get("source_file", "Unknown"),
                "parent_id":         pid,
                "topic_title":       meta.get("topic_title", img_id),
                "page_or_timestamp": page_or_ts,
                "score":             round(chunk_sim, 2),
                "similarity_score":  round(chunk_sim, 2),
                "chunk_text":        f"[Image: {img_id}] " + meta.get("topic_title", ""),
            })
            continue

        # Regular text chunk — collect any associated image IDs
        for img_id in (meta.get("image_ids", "") or "").split(","):
            img_id = img_id.strip()
            if img_id.startswith("IMG_") and img_id not in collected_image_ids:
                collected_image_ids.append(img_id)

        child_hits.append({
            "source":            meta.get("source_file", "Unknown"),
            "parent_id":         pid,
            "topic_title":       meta.get("topic_title", ""),
            "page_or_timestamp": page_or_ts,
            "score":             round(chunk_sim, 2),
            "similarity_score":  round(chunk_sim, 2),
            "chunk_text":        doc,
        })

        if pid and pid not in seen_parent_ids:
            seen_parent_ids.append(pid)

    # ── Phase 4: Resolve image manifest (cap 5, SQLite only) ──────────────
    image_manifest = resolve_image_manifest(collected_image_ids, active_branch, max_images=5)

    # Fetch up to 3 unique parent sections
    parent_store = load_parent_store(active_branch)
    parent_sections = []
    for pid in seen_parent_ids[:3]:
        ps = parent_store.get(pid)
        if ps:
            parent_sections.append(ps)

    # Enrich child hits with parent text (for the UI expander)
    for ch in child_hits:
        pid = ch.get("parent_id", "")
        ps = parent_store.get(pid, {})
        ch["parent_topic_title"] = ps.get("topic_title", ch.get("topic_title", ""))
        ch["parent_text"] = ps.get("content", "")

    # Build context block — extract a focused window around the matched child chunk
    MAX_CONTEXT_WINDOW = 25000  # chars (~6000 tokens)

    # Map parent_id -> ALL child chunk texts from this parent (multi-hit window extraction)
    pid_to_child_texts: dict[str, list[str]] = {}
    for ch in child_hits:
        pid = ch.get("parent_id", "")
        if pid:
            pid_to_child_texts.setdefault(pid, []).append(ch.get("chunk_text", ""))

    context_blocks: list[str] = []
    for ps in parent_sections:
        pid = ps.get("parent_id", "")
        # Collapse repetition loops in parent content
        content = _collapse_repetition_loops(ps["content"])
        if len(content) > MAX_CONTEXT_WINDOW:
            child_snippets = pid_to_child_texts.get(pid, [])
            if len(child_snippets) <= 1:
                focused = _extract_window(
                    content,
                    child_snippets[0] if child_snippets else "",
                    MAX_CONTEXT_WINDOW,
                    query_text=query,
                )
            else:
                # Multi-hit: extract a window around each distinct child chunk position,
                # merge overlapping windows, cap at 2 * MAX_CONTEXT_WINDOW total
                p_norm = content.replace("\r", "")
                half = MAX_CONTEXT_WINDOW // len(child_snippets)
                half = max(half, 2000)
                ranges: list[tuple[int, int]] = []
                for snippet in child_snippets:
                    c_clean = re.sub(r"^\[Document:[^\]]+\]\s*", "", snippet.replace("\r", "")).strip()
                    idx = -1
                    if c_clean:
                        for pl in (50, 30):
                            if c_clean[:pl]:
                                idx = p_norm.find(c_clean[:pl])
                                if idx != -1:
                                    break
                    if idx == -1:
                        words = [w for w in re.split(r"\W+", c_clean) if len(w) >= 3][:8]
                        if words:
                            pattern = r"\W+".join(re.escape(w) for w in words)
                            m = re.search(pattern, p_norm, re.IGNORECASE)
                            if m:
                                idx = m.start()
                    if idx == -1:
                        idx = 0
                    s = max(0, idx - half // 2)
                    e = min(len(p_norm), idx + half)
                    ranges.append((s, e))

                # Merge overlapping ranges
                ranges.sort()
                merged: list[list[int]] = []
                for s, e in ranges:
                    if merged and s <= merged[-1][1] + 200:
                        merged[-1] = [merged[-1][0], max(merged[-1][1], e)]
                    else:
                        merged.append([s, e])

                parts: list[str] = []
                for s, e in merged:
                    prefix = "...\n" if s > 0 else ""
                    suffix = "\n..." if e < len(p_norm) else ""
                    parts.append(prefix + p_norm[s:e] + suffix)
                focused = "\n\n".join(parts)
                MAX_COMBINED = MAX_CONTEXT_WINDOW * 2
                if len(focused) > MAX_COMBINED:
                    focused = focused[:MAX_COMBINED] + "\n..."
        else:
            focused = content

        context_blocks.append(
            f"--- Topic: {ps['topic_title']} (Source: {ps['source']}) ---\n{focused}"
        )

    context_str = "\n\n".join(context_blocks)

    # ── Phase 4: Append image manifest block to context string ────────────
    if image_manifest:
        img_lines = []
        for img_id, abs_path in image_manifest.items():
            fname = os.path.basename(abs_path)
            img_lines.append(f"  {img_id}: {fname}")
        context_str = (
            context_str
            + "\n\n--- Retrieved Images ---\n"
            + "\n".join(img_lines)
            + "\n\nWhen referencing an image in your answer, cite it as [IMG_xxxx]. "
            + "Do not invent image IDs not listed above."
        )

    return child_hits, context_str, parent_sections, image_manifest


def _fetch_legacy_context(results: dict) -> tuple[list, str]:
    """Build context from legacy (non-parent-child) child chunks."""
    retrieved_chunks: list[dict] = []
    context_blocks_legacy: list[str] = []

    for doc, meta, dist in zip(
        results["documents"][0],
        results["metadatas"][0],
        results["distances"][0],
    ):
        chunk_sim = max(0.0, 1.0 - dist)
        if chunk_sim < SIMILARITY_THRESHOLD:
            continue

        ts = meta.get("timestamp", "N/A")
        pg = meta.get("page", "N/A")
        src = meta.get("source_file", "Unknown")

        if pg != "N/A" and str(pg).strip():
            page_or_ts = f"Page {pg}" if isinstance(pg, int) or (isinstance(pg, str) and pg.isdigit()) else str(pg)
        elif ts != "N/A" and str(ts).strip():
            page_or_ts = f"[{ts}]" if not str(ts).startswith("[") else str(ts)
        else:
            page_or_ts = "N/A"

        retrieved_chunks.append({
            "source":             src,
            "page_or_timestamp":  page_or_ts,
            "score":              round(chunk_sim, 2),
            "similarity_score":   round(chunk_sim, 2),
            "chunk_text":         doc,
            "parent_id":          "",
            "topic_title":        "",
            "parent_topic_title": "",
            "parent_text":        "",
        })

        if len(context_blocks_legacy) < 3:
            context_blocks_legacy.append(f"[Source: {src} | {page_or_ts}]\n{doc}")

    return retrieved_chunks, "\n\n".join(context_blocks_legacy)
